export type Classification = {
  category: CategoryCode;
  confidence: number; // 0..1
  needsManual: boolean;
  matched: string[]; // сработавшие основы — для объяснения в UI
  scores: Partial<Record<CategoryCode, number>>;
};

export const CONFIDENCE_THRESHOLD = 0.5;

export function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/g, "е").replace(/[^\p{L}\p{N}\s]/gu, " ").replace(/\s+/g, " ").trim();
}

export function classify(text: string): Classification {
  const norm = normalize(text);
  const words = norm.split(" ");
  const scores: Partial<Record<CategoryCode, number>> = {};
  const matchedBy: Partial<Record<CategoryCode, string[]>> = {};

  for (const [cat, rules] of Object.entries(RULES) as [CategoryCode, Rule[]][]) {
    let s = 0;
    for (const [stem, w] of rules) {
      const hit = stem.startsWith("=")
        ? words.includes(stem.slice(1))
        : stem.includes(" ")
          ? norm.includes(stem)
          : words.some((wd) => wd.startsWith(stem));
      if (hit) {
        s += w;
        (matchedBy[cat] ??= []).push(stem.replace(/^=/, ""));
      }
    }
    if (s > 0) scores[cat] = s;
  }

  const ranked = (Object.entries(scores) as [CategoryCode, number][]).sort((a, b) => b[1] - a[1]);
  if (!ranked.length) return { category: "other", confidence: 0, needsManual: true, matched: [], scores };

  const [top, second] = ranked;
  const confidence = top[1] / (top[1] + (second?.[1] ?? 0) + 1);
  return {
    category: top[0],
    confidence: Math.round(confidence * 100) / 100,
    needsManual: confidence < CONFIDENCE_THRESHOLD,
    matched: [...new Set(matchedBy[top[0]])],
    scores,
  };
}
