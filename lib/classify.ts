//  1. Текст → нижний регистр, ё→е, убираем пунктуацию.
//  2. Для каждой категории — словарь основ слов (ru + kz) с весами.
//     Основа совпала с началом слова → +вес. Фразы (с пробелом) ищутся целиком.
//     Префикс «=» — только точное слово (казахское «су» не должно ловить «суббота»).
//  3. Побеждает категория с максимальной суммой.
//     Уверенность = top / (top + second + 1): высокая, только если отрыв большой.
