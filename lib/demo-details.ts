export function demoDetails(r: BaseReport, lang: Lang) {
  const i = lang === "kz" ? 1 : 0;
  const desc = pick(DESCRIPTIONS[r.category] ?? DESCRIPTIONS.other, r.id)[i];
  const resolution = r.status === "resolved" || r.status === "awaiting_confirmation"
    ? pick(RESOLUTIONS[r.category] ?? RESOLUTIONS.other, r.id)(num(r.id, 6, 60))[i]
    : null;
  return { description: desc, resolution };
}
